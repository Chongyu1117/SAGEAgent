"""
Calibrated Uncertainty Head — Post-hoc binary classifier predicting
p(|risk_partial - risk_oracle| > tau) via BCE + temperature scaling.

Training data is generated by enumerating clinical-ordering prefix masks
on patients with complete modalities.
"""

import itertools
import os
from typing import Dict, List, Optional, Tuple

import numpy as np
import torch
import torch.nn as nn
import torch.nn.functional as F
import torch.optim as optim
from torch.utils.data import DataLoader, TensorDataset


class CalibratedUncertaintyHead(nn.Module):
    """MLP predicting uncertainty from (embedding, mask).

    Output: p(|risk_partial - risk_oracle| > tau) in [0, 1]
    Training: BCEWithLogitsLoss on raw logits
    Inference: sigmoid(logit / temperature)

    Args:
        embedding_dim: predictor's embedding dimension (default 128).
        n_modalities:  number of modalities (default 4).
        hidden_dim:    MLP hidden layer size.
        mode:          "binary" (default) or "regression".
    """

    def __init__(
        self,
        embedding_dim: int = 128,
        n_modalities: int = 4,
        hidden_dim: int = 64,
        mode: str = "binary",
    ):
        super().__init__()
        self.embedding_dim = embedding_dim
        self.n_modalities = n_modalities
        self.hidden_dim = hidden_dim
        self.mode = mode
        input_dim = embedding_dim + n_modalities

        if mode == "regression":
            # Regression: Softplus output
            self.net = nn.Sequential(
                nn.Linear(input_dim, hidden_dim),
                nn.ReLU(),
                nn.Linear(hidden_dim, hidden_dim // 2),
                nn.ReLU(),
                nn.Linear(hidden_dim // 2, 1),
                nn.Softplus(),
            )
        else:
            # Binary: raw logits, activation applied in forward()
            self.net = nn.Sequential(
                nn.Linear(input_dim, hidden_dim),
                nn.ReLU(),
                nn.Linear(hidden_dim, hidden_dim // 2),
                nn.ReLU(),
                nn.Linear(hidden_dim // 2, 1),
            )

        # Temperature for post-hoc calibration (binary mode only).
        # Default T=1.0 (no scaling). Optimized after training via
        # calibrate_temperature() on validation set.
        self.temperature = nn.Parameter(torch.ones(1), requires_grad=False)

        self._init_weights()

    def _init_weights(self):
        for m in self.net:
            if isinstance(m, nn.Linear):
                nn.init.kaiming_normal_(m.weight, nonlinearity="relu")
                nn.init.zeros_(m.bias)

    def forward(
        self, embedding: torch.Tensor, mask: torch.Tensor
    ) -> torch.Tensor:
        """
        Args:
            embedding: (B, embedding_dim) from frozen predictor.
            mask:      (B, n_modalities) current acquired mask.

        Returns:
            (B,) uncertainty scores.
                Binary mode:     calibrated probability in [0, 1].
                Regression mode: non-negative discrepancy estimate.
        """
        x = torch.cat([embedding, mask], dim=-1)
        out = self.net(x).squeeze(-1)
        if self.mode == "binary":
            return torch.sigmoid(out / self.temperature)
        return out

    def get_logits(
        self, embedding: torch.Tensor, mask: torch.Tensor
    ) -> torch.Tensor:
        """Return raw logits before activation (binary mode).

        Used during training (BCEWithLogitsLoss) and temperature calibration.

        Args:
            embedding: (B, embedding_dim)
            mask:      (B, n_modalities)

        Returns:
            (B,) raw logits.
        """
        x = torch.cat([embedding, mask], dim=-1)
        return self.net(x).squeeze(-1)


# ═══════════════════════════════════════════════════════════════════════════
# Training data generation
# ═══════════════════════════════════════════════════════════════════════════
def generate_training_data(
    predictor: nn.Module,
    features: np.ndarray,
    masks: np.ndarray,
    device: str = "cuda",
    min_modalities: int = 2,
    clinical_ordering_only: bool = True,
    binary_threshold: Optional[float] = None,
    debug: bool = False,
) -> Tuple[np.ndarray, np.ndarray, np.ndarray]:
    """Generate (embedding, mask_subset, target) training triples.

    For each patient with ≥ ``min_modalities`` available modalities:
      - Compute risk with all available modalities (oracle)
      - Enumerate mask subsets, compute partial embedding + risk
      - Regression target: |risk_partial − risk_oracle|
      - Binary target (if binary_threshold is set): 1[|error| > threshold]

    When ``clinical_ordering_only=True`` (default), only the 4 clinical-chain
    prefix masks are used: [1,0,0,0], [1,1,0,0], [1,1,1,0], [1,1,1,1].

    When ``clinical_ordering_only=False``, all non-empty subsets are enumerated
    (all non-empty subsets).

    Args:
        predictor:              frozen SurvivalPredictor on *device*.
        features:               (N, n_mod, feat_dim) patient features.
        masks:                  (N, n_mod) availability masks.
        device:                 torch device.
        min_modalities:         skip patients with fewer available modalities.
        clinical_ordering_only: if True, use only clinical-chain prefix masks.
        binary_threshold:       if not None, binarize targets: 1[|error| > τ].
        debug:                  verbose.

    Returns:
        embeddings:  (M, embedding_dim) numpy array.
        mask_subsets: (M, n_mod) numpy array.
        targets:      (M,) numpy array.
                      Regression: |risk_partial − risk_oracle|
                      Binary:     0.0 or 1.0
    """
    predictor.eval()
    n_patients, n_mod, feat_dim = features.shape

    # Clinical ordering: Demo(0) → Rad(1) → Path(2) → Gen(3)
    # Prefix masks the agent actually encounters:
    clinical_prefix_masks = [
        np.array([1, 0, 0, 0], dtype=np.float32),  # demo only
        np.array([1, 1, 0, 0], dtype=np.float32),  # demo + rad
        np.array([1, 1, 1, 0], dtype=np.float32),  # demo + rad + path
        # [1,1,1,1] is the oracle (target=0), added separately below
    ]

    all_embeddings = []
    all_masks = []
    all_targets = []

    with torch.no_grad():
        for i in range(n_patients):
            avail = masks[i]  # (n_mod,)
            available_indices = [j for j in range(n_mod) if avail[j] > 0.5]

            if len(available_indices) < min_modalities:
                continue

            # Oracle: predict with all available modalities
            feat_full = torch.from_numpy(features[i]).float().unsqueeze(0).to(device)
            mask_full = torch.from_numpy(avail).float().unsqueeze(0).to(device)
            oracle_risk = predictor.get_risk_score(feat_full, mask_full).cpu().item()

            if clinical_ordering_only:
                # Only use clinical-chain prefix masks
                for sub_mask in clinical_prefix_masks:
                    # Skip if patient doesn't have all modalities in this prefix
                    if any(sub_mask[j] > 0.5 and avail[j] < 0.5 for j in range(n_mod)):
                        continue

                    sub_feat = features[i].copy()
                    for j in range(n_mod):
                        if sub_mask[j] < 0.5:
                            sub_feat[j] = 0.0

                    feat_t = torch.from_numpy(sub_feat).float().unsqueeze(0).to(device)
                    mask_t = torch.from_numpy(sub_mask.copy()).float().unsqueeze(0).to(device)

                    partial_risk = predictor.get_risk_score(feat_t, mask_t).cpu().item()
                    partial_emb = predictor.get_embedding(feat_t, mask_t).cpu().numpy()[0]

                    raw_target = abs(partial_risk - oracle_risk)
                    target = float(raw_target > binary_threshold) if binary_threshold is not None else raw_target

                    all_embeddings.append(partial_emb)
                    all_masks.append(sub_mask.copy())
                    all_targets.append(target)
            else:
                # Enumerate all non-empty strict subsets
                for size in range(1, len(available_indices)):
                    for subset in itertools.combinations(available_indices, size):
                        sub_mask = np.zeros(n_mod, dtype=np.float32)
                        for idx in subset:
                            sub_mask[idx] = 1.0

                        sub_feat = features[i].copy()
                        for j in range(n_mod):
                            if sub_mask[j] < 0.5:
                                sub_feat[j] = 0.0

                        feat_t = torch.from_numpy(sub_feat).float().unsqueeze(0).to(device)
                        mask_t = torch.from_numpy(sub_mask).float().unsqueeze(0).to(device)

                        partial_risk = predictor.get_risk_score(feat_t, mask_t).cpu().item()
                        partial_emb = predictor.get_embedding(feat_t, mask_t).cpu().numpy()[0]

                        raw_target = abs(partial_risk - oracle_risk)
                        target = float(raw_target > binary_threshold) if binary_threshold is not None else raw_target

                        all_embeddings.append(partial_emb)
                        all_masks.append(sub_mask)
                        all_targets.append(target)

            # Also add the full-mask case with target = 0
            full_emb = predictor.get_embedding(feat_full, mask_full).cpu().numpy()[0]
            all_embeddings.append(full_emb)
            all_masks.append(avail.copy())
            all_targets.append(0.0)

    embeddings = np.array(all_embeddings, dtype=np.float32)
    mask_subsets = np.array(all_masks, dtype=np.float32)
    targets = np.array(all_targets, dtype=np.float32)

    if debug:
        n_patients_used = sum(
            1 for i in range(n_patients)
            if sum(1 for j in range(n_mod) if masks[i][j] > 0.5) >= min_modalities
        )
        mode = "clinical-ordering" if clinical_ordering_only else "all-subsets"
        if binary_threshold is not None:
            pos_rate = targets.mean() if len(targets) > 0 else 0
            print(
                f"[CALIB] Generated {len(targets)} samples ({mode}, "
                f"binary τ={binary_threshold}) from {n_patients_used} patients "
                f"(positive rate: {pos_rate:.3f})"
            )
        else:
            print(
                f"[CALIB] Generated {len(targets)} training samples ({mode}) "
                f"from {n_patients_used} patients "
                f"(target range: [{targets.min():.4f}, {targets.max():.4f}], "
                f"mean: {targets.mean():.4f})"
            )

    return embeddings, mask_subsets, targets


